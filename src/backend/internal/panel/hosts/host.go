package hosts

import (
	"time"
)
//Host - запись о машине которой управляет панель
type Host struct{
	ID string // id держит в себе UUID хоста в строковом представлении
	Name string // название хоста(по идеи должен задавать его тело)
	CreatedAt time.Time// отслеживание времени когда было добавлено
}

